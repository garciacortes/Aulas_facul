  def PreencherGrid(self, index):
    linha = 0
    coluna = 0
    
    for i in range(63):
      index_model = self.model_Table_training.index(linha, coluna)
      if self.fontes[index, i] == 1:
        self.model_Table_training.setData(index_model, '#')
